#!/usr/bin/env python3
"""Six-layer 2-channel PeakNet1D PyTorch fake-QAT and Noodle2 export.

Reads ONLY the .npz generated by generate_ppg_dataset.py: no hidden data generation.
Trains on exactly quantized CHW inputs, then exports signed INT8 Noodle2 data.

Install: pip install numpy torch
Run: python train_peaknet_ppg_qat.py --dataset ppg_synthetic_100hz_256.npz
Fast test: python train_peaknet_ppg_qat.py --dataset small.npz --fp32-epochs 1 --qat-epochs 1
"""
from __future__ import annotations
import argparse
import copy
import json
import math
import random
from pathlib import Path
import numpy as np
import torch
import torch.nn as nn
import torch.nn.functional as F
from torch.utils.data import DataLoader,TensorDataset

# Model: PyTorch's N,C,T data format is CHW per sample. 1D kernels are
# serialized as [Cout,Cin,K], identical to Noodle2 2D [Cout,Cin,1,K].
SPEC = ((2,8,9),(8,16,7),(16,16,7),(16,16,7),(16,16,1),(16,1,1))
INPUT_SCALE=1/32
OUTPUT_SCALE=1/16  # logits [-8,7.9375], sigmoid applied on host


def round_away(x):
    return torch.where(x>=0,torch.floor(x+0.5),torch.ceil(x-0.5))


def fake_q(x,scale,lo=-128,hi=127):
    # STE; rounding matches Noodle2 requant's ties-away-from-zero convention.
    q=torch.clamp(round_away(x/scale),lo,hi)*scale
    return x+(q-x).detach()


class PeakNetPPG(nn.Module):
    def __init__(self):
        super().__init__()
        self.layers=nn.ModuleList([nn.Conv1d(ic,oc,k,padding=k//2,bias=True)
                                    for ic,oc,k in SPEC])
        # Calibrate the first five scales after FP32 warm-up, then freeze.
        self.register_buffer('activation_scales',torch.tensor([.02]*5+[OUTPUT_SCALE],dtype=torch.float32))
        self.qat_enabled=False

    def set_qat(self,on=True):
        self.qat_enabled=on

    def forward(self,x,return_intermediates=False):
        hidden=[]
        scale_in=INPUT_SCALE
        for i,layer in enumerate(self.layers):
            if self.qat_enabled:
                sw=layer.weight.detach().abs().max().clamp(min=1e-8)/127.0
                w=fake_q(layer.weight,sw,-127,127)
                b=fake_q(layer.bias,sw*scale_in,-2147483647,2147483647)
                z=F.conv1d(x,w,b,padding=layer.kernel_size[0]//2)
            else:
                z=layer(x)
            if i<5:
                z=F.relu(z)
            if self.qat_enabled:
                z=fake_q(z,self.activation_scales[i])
            if return_intermediates:
                hidden.append(z.detach())
            x=z
            scale_in=float(self.activation_scales[i].item())
        return (x,hidden) if return_intermediates else x


@torch.no_grad()
def calibrate_activations(model,loader,device='cpu',batches=12):
    was_qat=model.qat_enabled
    model.set_qat(False)
    model.eval()
    maxima=torch.full((5,),1e-4,dtype=torch.float64)
    for ix,(q,_,_) in enumerate(loader):
        if ix>=batches:break
        inp=q.to(device).float()*INPUT_SCALE
        _, intermediates = model(inp,return_intermediates=True)
        for j in range(5):
            maxima[j]=max(maxima[j].item(),intermediates[j].abs().max().item())
    for j in range(5):
        scale=max(1e-5, float(maxima[j])*1.35/127)
        model.activation_scales[j]=scale
    model.activation_scales[5]=OUTPUT_SCALE
    model.set_qat(was_qat)
    return model.activation_scales.cpu().tolist()


def parameter_count():
    return sum((ic*k+1)*oc for ic,oc,k in SPEC)


# -------------------------------------------------------------
# Exact Noodle2 signed INT8 export, Q31 shift and NumPy reference.
# -------------------------------------------------------------
def round_away_np(x):
    x=np.asarray(x,dtype=np.float64)
    return (np.sign(x)*np.floor(np.abs(x)+0.5)).astype(np.int64)


def q31(real_multiplier):
    if not np.isfinite(real_multiplier) or real_multiplier<=0:
        raise ValueError('requant multiplier must be finite and positive')
    significand,shift=math.frexp(float(real_multiplier))
    m=int(math.floor(significand*2**31+0.5))
    if m == 2**31:
        m=2**30
        shift+=1
    if not (-30 <= shift <= 30):
        raise ValueError(f'Noodle2 Q31 exponent out of range: {shift}')
    return m,shift


def make_quantized_layers(model):
    layers=[]
    s_in=INPUT_SCALE
    scales=model.activation_scales.detach().cpu().numpy().tolist()
    for ix,(module,s_out,spec) in enumerate(zip(model.layers,scales,SPEC)):
        w=module.weight.detach().cpu().numpy().astype(np.float64)
        b=module.bias.detach().cpu().numpy().astype(np.float64)
        sw=max(float(np.max(np.abs(w))),1e-8)/127.0
        qw=np.clip(round_away_np(w/sw),-127,127).astype(np.int8)
        qb=round_away_np(b/(s_in*sw))
        if np.any((qb < -(2**31))|(qb > (2**31-1))):
            raise ValueError('quantized bias overflows INT32')
        qm,shift=q31(s_in*sw/float(s_out))
        layers.append(dict(name=f'conv{ix+1:02d}',cin=spec[0],cout=spec[1],k=spec[2],
                           weights=qw,bias=qb.astype(np.int32),
                           input_scale=float(s_in),weight_scale=float(sw),
                           output_scale=float(s_out),multiplier=int(qm),shift=int(shift)))
        s_in=float(s_out)
    return layers


def requant_int(acc,multiplier,shift):
    """Exact port of Noodle2Quant.cpp, away-from-zero (INT32 acc)."""
    acc=np.asarray(acc,dtype=np.int64)
    if np.any((acc < -2**31)|(acc >= 2**31)):
        raise OverflowError('int32 accumulator overflow')
    right=31-int(shift)
    prod=acc*np.int64(multiplier)
    a=np.abs(prod)
    magnitude=(a+(np.int64(1) << np.int64(right-1))) >> np.int64(right)
    out=np.where(prod<0,-magnitude,magnitude)
    return np.clip(out,-128,127).astype(np.int8)


def run_exact(q, layers, return_intermediates=False):
    from numpy.lib.stride_tricks import sliding_window_view
    x=np.asarray(q,dtype=np.int8)
    if x.shape!=(2,256): raise ValueError(f'expected CHW (2,256), got {x.shape}')
    states=[]
    for ix,layer in enumerate(layers):
        k=layer['k'];oc=layer['cout']; ic=layer['cin']
        assert x.shape[0]==ic
        xp=np.pad(x.astype(np.int64),((0,0),(k//2,k//2)))
        win=sliding_window_view(xp,k,axis=1) # Cin,T,K
        patches=win.transpose(1,0,2).reshape(256,ic*k)
        weights=layer['weights'].reshape(oc,ic*k).astype(np.int64)
        acc=patches@weights.T+layer['bias'].astype(np.int64)[None,:]
        result=requant_int(acc,layer['multiplier'],layer['shift']).T.copy()
        if ix<5:result=np.maximum(result,0).astype(np.int8)
        x=result
        if return_intermediates:states.append(x.copy())
    return (x,states) if return_intermediates else x


def _format_bytes(data):
    return '\n'.join('    '+', '.join(map(str,data[i:i+22]))+',' for i in range(0,len(data),22))


def export_noodle2(model,outdir,example_q=None):
    outdir=Path(outdir);outdir.mkdir(parents=True,exist_ok=True)
    layers=make_quantized_layers(model)
    blocks=[];offsets=[];offset=0;descr=[]
    for l in layers:
        weights=l['weights'].reshape(-1).tobytes()
        biases=l['bias'].astype('<i4').tobytes()
        blocks.append(weights+biases)
        offsets.append(offset)
        descr.append({k:v for k,v in l.items() if k not in ('weights','bias')})
        descr[-1]['offset']=offset
        descr[-1]['weight_count']=len(weights)
        descr[-1]['bias_offset']=len(weights)
        offset+=len(weights)+len(biases)
    blob=b''.join(blocks)
    (outdir/'peaknet_ppg_int8.bin').write_bytes(blob)
    header=['#pragma once',
      '// Generated by quant_exact.py for Noodle2 v0.1.18 / PSRAM-patched runtime.',
      '// model has 2-channel CHW input (IR,RED); 256 samples at 100Hz.',
      '// Each layer: symmetric int8 weights + little-endian int32 biases.',
      '// NOODLE2 trained model; export only, requires host cross-validation.',
      '#include <Noodle2.h>',
      'namespace peaknet_ppg {',
      f'static const uint8_t data[{len(blob)}] = {{',
      _format_bytes(list(blob)),'};','struct Model {', '    noodle2::NoodleBuffer storage;']
    for l in layers:
        header.append(f'    noodle2::NoodleParams {l["name"]};')
    header.append('    Model() :')
    constructors=[]
    for l in layers:
        constructors.append(f'      {l["name"]}(0,{l["weights"].size},{l["weights"].size},{l["cout"]},noodle2::Quant({l["multiplier"]}L,{l["shift"]}))')
    header.append(',\n'.join(constructors)+' {}')
    header.append('    noodle2::Status bind_flash() {')
    header.append('        noodle2::Status st=storage.bind_flash(data,sizeof(data));')
    for l,pos in zip(layers,offsets):
        header.append(f'        if(st==noodle2::OK) st={l["name"]}.bind(storage,{pos});')
    header.extend(['        return st;','    }','};','} // namespace peaknet_ppg',''])
    (outdir/'peaknet_ppg_model.h').write_text('\n'.join(header))
    meta={'format':'Noodle2 0.1.18 per-layer [weights][biases] little-endian',
          'channels':['ir','red'],'layout':'CHW','window':256,'sample_rate_hz':100,
          'input_scale':INPUT_SCALE,'input_zero_point':0,'output_logit_scale':OUTPUT_SCALE,
          'output_zero_point':0,'preprocess':'PPGPreprocess.h raw uint16 to q-int8, per-channel mean+MAD',
          'q31_requant':'round-away-from-zero(acc * multiplier * 2^(shift-31)), saturate int8',
          'layers':descr,'parameter_bytes':len(blob)}
    (outdir/'model_manifest.json').write_text(json.dumps(meta,indent=2)+'\n')
    if example_q is not None:
        q=np.asarray(example_q,dtype=np.int8)
        output,states=run_exact(q,layers,True)
        (outdir/'golden_input_chw_i8.bin').write_bytes(q.tobytes())
        (outdir/'golden_logits_i8.bin').write_bytes(output.tobytes())
        for i,s in enumerate(states):
            (outdir/f'golden_conv{i+1:02d}_chw_i8.bin').write_bytes(s.tobytes())
        (outdir/'golden_logits.csv').write_text('index,int8_logit,sigmoid\n'+ '\n'.join(
          f'{j},{int(v)},{1/(1+np.exp(-float(v)*OUTPUT_SCALE)):.8f}' for j,v in enumerate(output[0]))+'\n')
    return layers,meta


def load_export(outdir):
    """Independently parse packed Noodle2 model into NumPy integer layers."""
    p=Path(outdir)
    manifest=json.loads((p/'model_manifest.json').read_text())
    blob=(p/'peaknet_ppg_int8.bin').read_bytes()
    assert len(blob)==manifest['parameter_bytes']
    layers=[]
    for d in manifest['layers']:
        pos=int(d['offset']); n=int(d['weight_count']); oc=int(d['cout']); ic=int(d['cin']); k=int(d['k'])
        assert n==oc*ic*k
        w=np.frombuffer(blob,dtype=np.int8,count=n,offset=pos).copy().reshape(oc,ic,k)
        b=np.frombuffer(blob,dtype='<i4',count=oc,offset=pos+n).copy()
        layers.append(dict(**{k:v for k,v in d.items() if k not in ('offset','weight_count','bias_offset')},
                           weights=w,bias=b))
    return layers,manifest


# -------------------------------------------------------------
# Train/validation/test pipeline on pre-generated NPZ splits.
# -------------------------------------------------------------
def weighted_bce(logits,y,mask):
    weight=1.0+18.0*y
    loss=F.binary_cross_entropy_with_logits(logits,y,reduction='none')
    return (loss*weight*mask).sum() / mask.sum().clamp(min=1.0)


def peaks_from_score(score,thr=.5,refractory=32):
    """Keep strongest candidates first; refractory in samples."""
    s=np.asarray(score).reshape(-1)
    candidates=np.flatnonzero((s>=thr) & (s>=np.r_[s[0],s[:-1]]) &
                               (s>=np.r_[s[1:],s[-1]]))
    chosen=[]
    for p in sorted(candidates,key=lambda i:-s[i]):
        if all(abs(int(p)-i)>=refractory for i in chosen):chosen.append(int(p))
    return sorted(chosen)


def matched_counts(pred,truth,tol=8):
    used=set();tp=0
    for p in pred:
        options=[(abs(int(t)-int(p)),i) for i,t in enumerate(truth)
                 if i not in used and abs(int(t)-int(p))<=tol]
        if options:
            _,i=min(options);used.add(i);tp+=1
    return tp,len(pred)-tp,len(truth)-tp


@torch.no_grad()
def evaluate(model,q,y,mask,truth,device,threshold=.50,integer=False):
    model.eval()
    if integer:layers=make_quantized_layers(model)
    tp=fp=fn=0
    bs=64
    for start in range(0,len(q),bs):
        sl=slice(start,start+bs)
        if integer:
            pred=np.stack([run_exact(qq,layers)[0] for qq in q[sl]])
            score=1.0/(1.0+np.exp(-np.clip(pred.astype(np.float64)*OUTPUT_SCALE,-16,16)))
        else:
            inp=torch.from_numpy(q[sl].copy()).float().to(device)*INPUT_SCALE
            score=torch.sigmoid(model(inp)).cpu().numpy()[:,0]
        for i,s in enumerate(score):
            valid=mask[start+i,0].astype(bool)
            candidates=[j for j in peaks_from_score(s,threshold) if valid[j]]
            tt=np.asarray(truth[start+i],dtype=int)
            tt=tt[valid[tt]]
            a,b,c=matched_counts(candidates,tt)
            tp+=a;fp+=b;fn+=c
    prec=tp/(tp+fp) if tp+fp else 0
    rec=tp/(tp+fn) if tp+fn else 0
    return {'precision':prec,'recall':rec,'f1':2*prec*rec/(prec+rec) if prec+rec else 0,
            'TP':tp,'FP':fp,'FN':fn}




def load_split(z,split):
    required=[f'{split}_{name}' for name in ('q','y','mask','peaks')]
    for name in required:
        if name not in z: raise KeyError(f'Missing {name}; run the generator first.')
    q=np.asarray(z[f'{split}_q'],dtype=np.int8)
    y=np.asarray(z[f'{split}_y'],dtype=np.float32)
    mask=np.asarray(z[f'{split}_mask'],dtype=np.float32)
    padded=np.asarray(z[f'{split}_peaks'],dtype=np.int16)
    if q.ndim!=3 or q.shape[1:]!=(2,256):raise ValueError(f'Invalid {split} CHW input {q.shape}')
    if y.shape!=(len(q),1,256) or mask.shape!=y.shape or padded.shape[0]!=len(q):
        raise ValueError(f'Invalid {split} label shapes')
    peaks=[r[r>=0].astype(np.int32) for r in padded]
    if not np.isfinite(y).all() or not np.isfinite(mask).all(): raise ValueError('invalid labels/masks')
    return q,y,mask,peaks


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--dataset',default='ppg_synthetic_100hz_256.npz')
    p.add_argument('--out',default='runs/peaknet_ppg_qat')
    p.add_argument('--fp32-epochs',type=int,default=5)
    p.add_argument('--qat-epochs',type=int,default=12)
    p.add_argument('--batch',type=int,default=64)
    p.add_argument('--lr',type=float,default=1e-3)
    p.add_argument('--seed',type=int,default=20261108)
    p.add_argument('--threads',type=int,default=2)
    a=p.parse_args()
    if a.fp32_epochs<0 or a.qat_epochs<=0 or a.batch<=0:p.error('Need qat-epochs > 0, fp32-epochs >= 0, batch > 0')
    torch.set_num_threads(a.threads)
    random.seed(a.seed);np.random.seed(a.seed);torch.manual_seed(a.seed)
    if torch.cuda.is_available():torch.cuda.manual_seed_all(a.seed)
    device='cuda' if torch.cuda.is_available() else 'cpu'
    with np.load(a.dataset,allow_pickle=False) as z:
        if 'metadata_json' not in z: raise ValueError('Missing generator metadata')
        meta=json.loads(str(z['metadata_json']))
        if meta['channels']!=['ir','red'] or meta['fs_hz']!=100 or meta['window']!=256:
            raise ValueError(f'Incompatible dataset preprocessing/shape {meta}')
        if abs(float(meta['input_scale'])-INPUT_SCALE)>1e-10:
            raise ValueError('Input scale mismatch')
        qtr,ytr,mtr,_=load_split(z,'train')
        qva,yva,mva,pva=load_split(z,'val')
        qte,yte,mte,pte=load_split(z,'test')
    out=Path(a.out);out.mkdir(parents=True,exist_ok=True)
    loader=DataLoader(TensorDataset(torch.from_numpy(qtr.copy()),
                 torch.from_numpy(ytr.copy()),torch.from_numpy(mtr.copy())),
                 batch_size=a.batch,shuffle=True)
    model=PeakNetPPG().to(device)
    print('Dataset:',a.dataset, 'shapes:',qtr.shape,qva.shape,qte.shape)
    print('Architecture:',SPEC,'parameters:',parameter_count(),'device:',device,flush=True)
    opt=torch.optim.AdamW(model.parameters(),lr=a.lr,weight_decay=1e-5)
    logs=[]
    best_state=None;best_f1=-1.0;best_epoch=-1
    total=a.fp32_epochs+a.qat_epochs
    for epoch in range(total):
        qat=epoch>=a.fp32_epochs
        if epoch==a.fp32_epochs:
            scales=calibrate_activations(model,loader,device)
            print('Frozen activation scales:',[round(float(s),8) for s in scales],flush=True)
        model.set_qat(qat)
        model.train();running=0.0
        for q,y,mask in loader:
            x=q.to(device).float()*INPUT_SCALE
            y=y.to(device);mask=mask.to(device)
            opt.zero_grad(set_to_none=True)
            logits=model(x)
            loss=weighted_bce(logits,y,mask)
            loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(),2.0)
            opt.step()
            running+=loss.item()*len(q)
        vm=evaluate(model,qva,yva,mva,pva,device,integer=False)
        avg_loss=running/len(qtr)
        print(f'epoch {epoch+1:02d}/{total} {"QAT " if qat else "FP32"} '
              f'loss={avg_loss:.4f} val_F1={vm["f1"]:.4f} '
              f'P={vm["precision"]:.4f} R={vm["recall"]:.4f}',flush=True)
        logs.append(dict(epoch=epoch+1,phase='QAT' if qat else 'FP32',loss=avg_loss,val=vm))
        if qat and vm['f1']>best_f1:
            best_state=copy.deepcopy(model.state_dict());best_f1=vm['f1'];best_epoch=epoch+1
    if best_state is not None:model.load_state_dict(best_state)
    model.set_qat(True);model.eval()
    print('Restored best QAT epoch:',best_epoch,'F1:',best_f1,flush=True)
    val_fake=evaluate(model,qva,yva,mva,pva,device,integer=False)
    val_int=evaluate(model,qva,yva,mva,pva,device,integer=True)
    test_fake=evaluate(model,qte,yte,mte,pte,device,integer=False)
    test_int=evaluate(model,qte,yte,mte,pte,device,integer=True)
    print('Validation QAT:',val_fake,'Noodle2-exact INT8:',val_int,flush=True)
    print('Test QAT:',test_fake,'Noodle2-exact INT8:',test_int,flush=True)
    torch.save(dict(model=model.state_dict(),spec=SPEC,
             activation_scales=model.activation_scales.detach().cpu().tolist(),
             dataset_metadata=meta),out/'peaknet_ppg_qat.pt')
    export_dir=out/'noodle2_export'
    layers,manifest=export_noodle2(model,export_dir,example_q=qte[0])
    metrics=dict(model='PeakNet1D-PPG',sample_rate_hz=100,train_windows=len(qtr),
           val_windows=len(qva),test_windows=len(qte),parameters=parameter_count(),
           best_qat_epoch=best_epoch,val_qat=val_fake,val_exact_int8=val_int,
           test_qat=test_fake,test_exact_int8=test_int,history=logs,
           caution='Synthetic evaluation only; no verified real PPG beat labels')
    (out/'metrics.json').write_text(json.dumps(metrics,indent=2)+'\n')
    print('Saved model/checkpoint/metrics:',out.resolve(),flush=True)
    print('Noodle2 INT8 model/header/golden tensor:',export_dir.resolve(),flush=True)

if __name__=='__main__':main()
